def compile_staging(staging_root: Path) -> None:
    for relative in EXPECTED_TARGETS:
        if relative.endswith(".py"):
            py_compile.compile(
                str(staging_root / relative),
                doraise=True,
            )


def backup_existing(root: Path, backup_root: Path) -> set[str]:
    existed: set[str] = set()
    backup_root.mkdir(parents=True, exist_ok=False)
    for relative in EXPECTED_TARGETS:
        source = root / relative
        if source.is_file():
            existed.add(relative)
            destination = backup_root / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
    views = root / "app" / "views"
    if views.is_dir():
        shutil.copytree(views, backup_root / "_full_app_views")
    return existed


def ensure_legacy_demo(root: Path) -> bool:
    legacy = root / "app" / "demo_legacy_v0_4_2.py"
    if legacy.exists():
        return False
    shutil.copy2(root / "app" / "demo.py", legacy)
    return True


def atomic_replace_all(
    root: Path,
    staging_root: Path,
) -> list[str]:
    replaced: list[str] = []
    for relative in EXPECTED_TARGETS:
        source = staging_root / relative
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        os.replace(source, target)
        replaced.append(relative)
    return replaced


def rollback(
    root: Path,
    backup_root: Path,
    existed: set[str],
    replaced: list[str],
    legacy_created: bool,
) -> None:
    print("开始回滚已经替换的文件...", file=sys.stderr)
    for relative in reversed(replaced):
        target = root / relative
        backup = backup_root / relative
        if relative in existed and backup.exists():
            restore_temp = target.with_name(target.name + ".rollback")
            restore_temp.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(backup, restore_temp)
            os.replace(restore_temp, target)
        elif target.exists():
            target.unlink()
    if legacy_created:
        legacy = root / "app" / "demo_legacy_v0_4_2.py"
        if legacy.exists():
            legacy.unlink()
    print("回滚完成。", file=sys.stderr)


def run_checked(root: Path, command: list[str]) -> None:
    print("$ " + " ".join(command))
    subprocess.run(command, cwd=root, check=True)


def run_post_write_checks(root: Path) -> None:
    python_files = [relative for relative in EXPECTED_TARGETS if relative.endswith(".py")]
    run_checked(root, [sys.executable, "-m", "py_compile", *python_files])
    run_checked(
        root,
        [
            sys.executable,
            "-c",
            "import app.audit_core, app.plots, app.ui;"
            " print('module-import-ok')",
        ],
    )
    run_checked(
        root,
        [
            sys.executable,
            "-m",
            "pytest",
            "-q",
            "tests/test_audit_core.py",
            "tests/test_demo_smoke.py",
        ],
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="只执行预检并打印写入计划。",
    )
    args = parser.parse_args()

    root = Path.cwd().resolve()
    if list(FILES) != EXPECTED_TARGETS:
        raise SystemExit("内置目标文件清单与 EXPECTED_TARGETS 不一致。")
    if any(not content.strip() for content in FILES.values()):
        raise SystemExit("内置目标文件存在空内容。")

    check_repository_root(root)
    check_experiment_files(root)
    print_preflight(root)
    warn_dirty_worktree(root)
    if args.dry_run:
        print("DRY RUN 完成：未创建目录、未备份、未覆盖文件。")
        return 0

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    staging_root = root / ".demo_staging" / f"v073_{timestamp}"
    backup_root = root / ".demo_backup" / f"v073_{timestamp}"
    staging_root.mkdir(parents=True, exist_ok=False)
    replaced: list[str] = []
    existed: set[str] = set()
    legacy_created = False
    try:
        write_staging(root, staging_root)
        compile_staging(staging_root)
        print(f"暂存编译通过：{staging_root.relative_to(root)}")

        existed = backup_existing(root, backup_root)
        legacy_created = ensure_legacy_demo(root)
        replaced = atomic_replace_all(root, staging_root)
        run_post_write_checks(root)
    except Exception as exc:
        print(f"写入或验证失败：{exc}", file=sys.stderr)
        if backup_root.exists():
            rollback(root, backup_root, existed, replaced, legacy_created)
        return 1
    finally:
        if staging_root.exists():
            shutil.rmtree(staging_root, ignore_errors=True)

    print("写入与验证完成。备份保留在：")
    print(f"  {backup_root.relative_to(root)}")
    print("目标文件 SHA256：")
    for relative in EXPECTED_TARGETS:
        print(f"  {sha256(root / relative)}  {relative}")
    if legacy_created:
        print("已保留旧版入口：app/demo_legacy_v0_4_2.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
