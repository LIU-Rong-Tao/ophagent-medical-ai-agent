def run_git(root: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", *args],
        cwd=root,
        text=True,
        encoding="utf-8",
        errors="replace",
        capture_output=True,
        check=False,
    )
    return result.stdout.strip() if result.returncode == 0 else "unknown"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def check_repository_root(root: Path) -> None:
    required = [root / ".git", root / "app" / "demo.py", root / "experiments" / "summary"]
    missing = [str(path.relative_to(root)) for path in required if not path.exists()]
    if missing:
        raise SystemExit("当前目录不是完整 OphAgent 仓库，缺少：" + ", ".join(missing))


def check_experiment_files(root: Path) -> None:
    missing = [path for path in EXPERIMENT_FILES if not (root / path).is_file()]
    if missing:
        print("缺少实验文件，停止写入：", file=sys.stderr)
        for path in missing:
            print(f"  - {path}", file=sys.stderr)
        raise SystemExit(2)


def warn_dirty_worktree(root: Path) -> None:
    output = run_git(root, "status", "--short", "--untracked-files=all")
    relevant: list[str] = []
    for line in output.splitlines():
        normalized = line.replace("\\", "/").strip('"')
        if any(prefix in normalized for prefix in IGNORED_DIRTY_PREFIXES):
            continue
        relevant.append(line)
    if relevant:
        print("WARNING：工作区存在其他改动；脚本只覆盖目标文件，不会自动停止：")
        for line in relevant[:30]:
            print(f"  {line}")


def print_preflight(root: Path) -> None:
    print(f"仓库：{root}")
    print(f"当前分支：{run_git(root, 'branch', '--show-current')}")
    print(f"当前 HEAD：{run_git(root, 'rev-parse', 'HEAD')}")
    print("将写入的文件：")
    for path in EXPECTED_TARGETS:
        print(f"  - {path}")
    print("将备份的现有内容：")
    for path in EXPECTED_TARGETS:
        if (root / path).exists():
            print(f"  - {path}")
    if (root / "app" / "views").exists():
        print("  - app/views/（完整目录快照）")


def write_staging(root: Path, staging_root: Path) -> None:
    for relative, content in FILES.items():
        target = staging_root / relative
