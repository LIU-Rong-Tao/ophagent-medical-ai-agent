def backup_existing(root: Path, backup_root: Path) -> set[str]:
    backup_root.mkdir(parents=True, exist_ok=False)
    existed: set[str] = set()
    for relative in EXPECTED_TARGETS:
        source = root / relative
        if source.is_file():
            existed.add(relative)
            target = backup_root / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
    return existed


def install_staging(root: Path, staging_root: Path) -> None:
    for relative in EXPECTED_TARGETS:
        source = staging_root / relative
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_name(target.name + ".v073ext.tmp")
        shutil.copy2(source, temporary)
        os.replace(temporary, target)


