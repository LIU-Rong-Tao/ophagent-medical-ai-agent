def warn_dirty_worktree(root: Path) -> None:
    output = git_output(root, "status", "--short", "--untracked-files=all")
    relevant = []
    for line in output.splitlines():
        normalized = line.replace("\\", "/").strip('"')
        if any(prefix in normalized for prefix in IGNORED_DIRTY_PREFIXES):
            continue
        relevant.append(line)
    if relevant:
        print("WARNING：工作区存在其他改动；脚本只覆盖本轮目标文件：")
        for line in relevant[:30]:
            print(f"  {line}")


